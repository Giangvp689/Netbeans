    private void btnDatLichActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDatLichActionPerformed
      try {
        // ===== 1. LẤY DỮ LIỆU =====
        String hoTen = txtHoTen.getText().trim();
        String sdt = txtSDT.getText().trim();
        String gioiTinh = cbGioiTinh.getSelectedItem().toString();
        String ghiChu = txtGhiChu.getText().trim();

        java.util.Date utilNgaySinh = dateNgaySinh.getDate();
        java.util.Date utilNgayKham = dateNgay.getDate();

        if (hoTen.isEmpty() || sdt.isEmpty() || utilNgayKham == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đủ thông tin!");
            return;
        }

        java.sql.Date ngaySinh =
                (utilNgaySinh != null)
                        ? new java.sql.Date(utilNgaySinh.getTime())
                        : null;

        java.sql.Date ngayKham =
                new java.sql.Date(utilNgayKham.getTime());

        LocalTime lt = timeGio.getTime();
        java.sql.Time gioKham =
                (lt != null) ? java.sql.Time.valueOf(lt) : null;

        // ===== 2. LẤY BÁC SĨ =====
        BacSi bs = getBacSiSelected();
        if (bs == null) {
            JOptionPane.showMessageDialog(this, "Chưa chọn bác sĩ!");
            return;
        }

        // ===== 3. INSERT ĐẶT LỊCH (KHÔNG TẠO BỆNH NHÂN) =====
        String sql = """
            INSERT INTO DatLich
            (id_bn, hoten_nv, sdt_nv, gioitinh_nv, ngaysinh_nv,
             ghichu, id_bs, ngaykham, giokham)
            VALUES (?,?,?,?,?,?,?,?,?)
        """;

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setNull(1, java.sql.Types.INTEGER); // ❗ id_bn = NULL
            ps.setString(2, hoTen);
            ps.setString(3, sdt);
            ps.setString(4, gioiTinh);
            ps.setDate(5, ngaySinh);
            ps.setString(6, ghiChu);
            ps.setInt(7, bs.getId_bs());
            ps.setDate(8, ngayKham);
            ps.setTime(9, gioKham);

            ps.executeUpdate();
        }

        // ===== 4. LOAD LẠI LỊCH =====
        loadLichTrongNgay(bs.getId_bs(), utilNgayKham);

        JOptionPane.showMessageDialog(this, "Đặt lịch thành công!");

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Lỗi khi đặt lịch!");
    }
    }//GEN-LAST:event_btnDatLichActionPerformed

