    private void loadLichTrongNgay(int idBacSi, java.util.Date utilDate) {

    if (utilDate == null) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn ngày khám");
        return;
    }

    // Convert util.Date -> sql.Date
    java.sql.Date sqlDate = new java.sql.Date(utilDate.getTime());

    DefaultTableModel model = (DefaultTableModel) tblMedical.getModel();
    model.setRowCount(0);

    String sql = """
        SELECT dl.id_lich, dl.ngaykham, dl.giokham,
               bn.hoten, bn.sdt, dl.trangthai
        FROM DatLich dl
        LEFT JOIN BenhNhan bn ON dl.id_bn = bn.id_bn
        WHERE dl.id_bs = ? AND dl.ngaykham = ?
        ORDER BY dl.giokham
    """;

    try (Connection con = DBConnection.getConnection();
         PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setInt(1, idBacSi);
        ps.setDate(2, sqlDate);

        ResultSet rs = ps.executeQuery();
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id_lich"),
                rs.getDate("ngaykham"),
                rs.getTime("giokham"),
                rs.getString("hoten"),
                rs.getString("sdt"),
                rs.getString("trangthai")
            });
        }

    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Lỗi load lịch khám");
    }
}
    
private void hienThiLichTheoNgay() {

    BacSi bs = getBacSiSelected();
    if (bs == null) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn bác sĩ");
        return;
    }

    java.util.Date utilDate = dateNgay.getDate();
    if (utilDate == null) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn ngày");
        return;
    }

    java.sql.Date sqlDate = new java.sql.Date(utilDate.getTime());

    List<DatLich> list =
        datlichctrl.getLichTheoNgay(bs.getId_bs(), sqlDate);

    DefaultTableModel model = new DefaultTableModel();
    model.setColumnIdentifiers(new Object[]{
        "ID_LICH", 
        "Ngày khám",
        "Giờ khám",
        "Bệnh nhân",
        "SĐT",
        "Giới tính",
        "Trạng thái",
        "Ghi chú"
    });

    for (DatLich dl : list) {
        model.addRow(new Object[]{
            dl.getId_lich(),
            dl.getNgaykham(),
            dl.getGiokham(),
            dl.getHoten_nv(),
            dl.getSdt_nv(),
            dl.getGioitinh_nv(),
            dl.getTrangthai(),
            dl.getGhichu()
        });
    }

    tblMedical.setModel(model);
    
    tblMedical.getColumnModel().getColumn(0).setMinWidth(0);
    tblMedical.getColumnModel().getColumn(0).setMaxWidth(0);
    tblMedical.getColumnModel().getColumn(0).setPreferredWidth(0);

}





