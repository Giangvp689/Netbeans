    private void jTextField6KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTextField6KeyReleased
          String keyword = jTextField6.getText(); // Lấy từ khóa bạn vừa nhập
    String searchType = jComboBox4.getSelectedItem().toString(); // "Mã NV", "Tên NV", "Chức vụ"
    
    // Chuyển đổi lựa chọn của ComboBox sang tên cột tương ứng trong SQL
    String column = "hoten"; // Mặc định là tìm theo tên
    if (searchType.equals("Mã NV")) {
        column = "id_nv";
    } else if (searchType.equals("Chức vụ")) {
        column = "chucvu";
    }

    // Tiến hành truy vấn SQL với từ khóa tìm kiếm
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); // Xóa bảng trước khi hiện kết quả tìm được

    // Dùng LIKE ? và % để tìm kiếm tương đối (chỉ cần chứa từ khóa là hiện)
    String sql = "SELECT id_nv, hoten, ngaysinh, gioitinh, sdt, chucvu, trangthai FROM NhanVien WHERE " + column + " LIKE ?";
    
    try (java.sql.Connection conn = Model.DBConnection.getConnection();
         java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {
        
        ps.setString(1, "%" + keyword + "%");
        java.sql.ResultSet rs = ps.executeQuery();
        
        while (rs.next()) {
            java.util.Vector row = new java.util.Vector();
            row.add(rs.getInt("id_nv"));
            row.add(rs.getString("hoten"));
            row.add(rs.getDate("ngaysinh"));
            row.add(rs.getString("gioitinh"));
            row.add(rs.getString("sdt"));
            row.add(rs.getString("chucvu"));
            row.add(rs.getString("trangthai"));
            
            model.addRow(row);
        }
    } catch (Exception e) {
        e.printStackTrace();
    }  
    }//GEN-LAST:event_jTextField6KeyReleased


