    public void loadTable() {
    // 1. Lấy model của bảng và xóa dữ liệu cũ
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); 

    // 2. Định nghĩa các cột hiển thị (tùy chỉnh theo ý bạn)
    model.setColumnIdentifiers(new Object[]{
        "ID", "Họ Tên", "Ngày Sinh", "Giới Tính","Địa chỉ", "SĐT", "Chức Vụ", "Trạng Thái"
    });

    // 3. Câu lệnh SQL truy vấn dữ liệu
    String sql = "SELECT id_nv, hoten, ngaysinh, gioitinh, diachi, sdt, chucvu, trangthai FROM NhanVien";

    try (Connection conn = DBConnection.getConnection(); 
         PreparedStatement ps = conn.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            Vector row = new Vector();
            row.add(rs.getInt("id_nv"));
            row.add(rs.getString("hoten"));
            row.add(rs.getDate("ngaysinh"));
            row.add(rs.getString("gioitinh"));
            row.add(rs.getString("diachi"));
            row.add(rs.getString("sdt"));
            row.add(rs.getString("chucvu"));
            row.add(rs.getString("trangthai"));

            model.addRow(row); // Thêm dòng dữ liệu vào bảng
        }
    } catch (Exception e) {
        // Sử dụng TênLớp.this để tránh lỗi từ khóa 'this' trong các context khác nhau
        JOptionPane.showMessageDialog(EmployeesPanel.this, "Lỗi nạp dữ liệu: " + e.getMessage());
        e.printStackTrace();
    }
}

