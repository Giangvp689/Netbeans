private int tinhTuoi(java.util.Date ngaySinh) {
    if (ngaySinh == null) return 0;
    LocalDate birth =
        ngaySinh.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
    LocalDate now = LocalDate.now();

    return Period.between(birth, now).getYears();
}



