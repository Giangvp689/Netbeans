private DefaultListModel<String> modelDay = new DefaultListModel<>();
private Map<String, java.sql.Date> mapNgay = new HashMap<>();

private void loadListDay(int idBn) {
    modelDay.clear();
    mapNgay.clear();

    List<java.sql.Date> list =
        benhAnController.getNgayKhamByBenhNhan(idBn);

    SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");

    for (java.sql.Date d : list) {
        String text = sdf.format(d);
        modelDay.addElement(text);
        mapNgay.put(text, d);   // 🔥 mapping
    }

    listday.setModel(modelDay);
}



private DefaultListModel<String> modelService = new DefaultListModel<>();
private Map<String, DichVu> mapService = new HashMap<>();

private void initServiceEvents() {
    listservice.addListSelectionListener(e -> {
        if (!e.getValueIsAdjusting()) {
            tinhTongTienDichVu();
            loadTableHoaDon(currentIdBa);
        }
    });
}
private void tinhTongTienDichVu() {
    double tong = 0;

    List<String> selectedValues = listservice.getSelectedValuesList();
    for (String s : selectedValues) {
        DichVu dv = mapService.get(s);
        if (dv != null) {
            tong += dv.getDongia();
        }
    }

    lblTongTienDV.setText(String.format("%.0f", tong)+"  VND ");
}

private void loadListService() {
    modelService.clear();
    mapService.clear();

    for (DichVu dv : dichVuController.getAllDichVu()) {
        String text = dv.getTendv()+ " - " + dv.getDongia();
        modelService.addElement(text);
        mapService.put(text, dv); // 🔥 mapping
    }

    listservice.setModel(modelService);

   
}

    private ChiTietDonThuocDAO chiTietDonThuocDAO=new ChiTietDonThuocDAO();
    private void loadTableDonThuoc(int idBa) {

    int idDt = donThuocController.getDonThuocByBenhAn(idBa);
      if (idDt <= 0) {
        txtGhiChu.setText("");   // 🔥 clear nếu chưa có
        return;
    }

    DefaultTableModel model =
        (DefaultTableModel) tblDonThuoc.getModel();

    model.setColumnIdentifiers(new Object[]{
        "ID_CT",
        "Tên thuốc",
        "Số lượng",
        "Liều dùng",
        "Đơn giá"
    });

    model.setRowCount(0);

    for (ChiTietDonThuoc ct :
            chiTietDonThuocDAO.getByDonThuoc(idDt)) {

        model.addRow(new Object[]{
            ct.getId_ctdt(),
            ct.getTenThuoc(),
            ct.getSoluong(),
            ct.getLieudung(),
            ct.getDongia()
        });
    }

    updateTongTien(); // nhớ gọi
       // ===== LOAD GHI CHÚ =====
    String ghiChu = donThuocController.getGhiChuDonThuoc(idDt);
    txtGhiChu.setText(ghiChu);
}

private void updateTongTien() {
    DefaultTableModel model = (DefaultTableModel) tblDonThuoc.getModel();
    double tong = 0;

    for (int i = 0; i < model.getRowCount(); i++) {
        int soLuong = Integer.parseInt(
            model.getValueAt(i, 2).toString()
        );

        double donGia = Double.parseDouble(
            model.getValueAt(i, 4).toString()
        );

        tong += soLuong * donGia;
    }

    lblTotal.setText(String.format("%,.0f VND", tong));
}



