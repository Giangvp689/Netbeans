    private void btnAddMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnAddMouseClicked
         try {
        // 1. Validation
        if(txtHoten.getText().isEmpty() || txtDienThoai.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Vui lòng nhập thông tin bệnh nhân");
            return;
        }
        
        // 2. Kiểm tra bệnh nhân đã có chưa
        String sdt = txtDienThoai.getText().trim();
        BenhNhan bnExist = controller.getBenhNhanBySdt(sdt);  // Gọi Controller
        
        int idBn;
        
        if (bnExist != null) {
            // Dùng bệnh nhân cũ
            idBn = bnExist.getId_bn();
            // Có thể cập nhật thông tin nếu muốn
        } else {
            // Thêm bệnh nhân mới
            BenhNhan bn = getFormData();
            idBn = controller.insertBenhNhan(bn);  // Gọi Controller
            if (idBn <= 0) {
                JOptionPane.showMessageDialog(this, "Thêm bệnh nhân thất bại");
                return;
            }
        }

        // 3. Tạo phiếu khám mới (luôn tạo mới)
        PhieuKham pk = new PhieuKham();
        pk.setId_bn(idBn);
        pk.setHoten_nv(txtHoten.getText());
        pk.setSdt_nv(sdt);
        pk.setId_bs(getBacSiSelected().getId_bs());
        pk.setId_nv_don(getNhanVienSelected().getId_nv());
        pk.setLoaikham(cboLoai.getSelectedItem().toString());
        pk.setPhongkham(cboPhong.getSelectedItem().toString());
        
        LocalTime localTime = timegio.getTime();
        if (localTime != null) {
            pk.setGiokham(Time.valueOf(localTime));
        }
        pk.setTrangthai("Đã đến");

        PhieuKhamController pkcontr = new PhieuKhamController();
        pkcontr.addPhieuKham(pk);  // Gọi Controller

        // 4. Tạo bệnh án mới với ngày hôm nay
        BenhAn ba = new BenhAn();
        ba.setId_bn(idBn);
        ba.setId_bs(getBacSiSelected().getId_bs());
        ba.setNgaykhambenhan(new java.sql.Date(System.currentTimeMillis()));
        ba.setTrangthai("Chờ khám");

        benhAnController.addBenhAn(ba);  // Gọi Controller

        // 5. Thông báo
        loadTable();
        JOptionPane.showMessageDialog(this, "✅ Đã thêm phiếu khám mới thành công!");
        
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
    }
    }//GEN-LAST:event_btnAddMouseClicked

