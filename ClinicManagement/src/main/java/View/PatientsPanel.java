  private void loadTableHoaDon(int idHd) {

    DefaultTableModel model = new DefaultTableModel();
    model.setColumnIdentifiers(new Object[]{
        "Loại", "Tên", "Số lượng", "Đơn giá", "Thành tiền"
    });

    for (Object[] row : hoaDonController.getHoaDonTableData(idHd)) {
        model.addRow(row);
    }

    tblHoadon.setModel(model);

    // tổng tiền = sum ChiTiet_HoaDon
    BigDecimal tong =
        hoaDonController.getTongTien(idHd);

    txtHDTotal.setText(
        tong != null ? tong.toString() : "0"
    );
}


    
    
    
    
