private void loadTableThuoc() {
    DefaultTableModel model = new DefaultTableModel();
    model.setColumnIdentifiers(new Object[]{
        "ID",
        "Tên thuốc",
        "Loại",
        "Số lượng",
        "Đơn vị",
        "Giá bán",
        "Hạn sử dụng",
        "Ghi chú"
    });

    for (Object[] row : thuocCtrl.getThuocTable()) {
        model.addRow(row);
    }

    tblThuoc.setModel(model);

    // Ẩn ID
    tblThuoc.getColumnModel().getColumn(0).setMinWidth(0);
    tblThuoc.getColumnModel().getColumn(0).setMaxWidth(0);
    tblThuoc.getColumnModel().getColumn(0).setPreferredWidth(0);
}
private void loadLoaiThuocCbo() {
    cboLoaiSearch.removeAllItems();

    // Mặc định
    cboLoaiSearch.addItem("Tất cả");

    for (String loai : thuocCtrl.getAllLoaiThuoc()) {
        cboLoaiSearch.addItem(loai);
    }
}
private void loadTableSearch() {

    if (cboLoaiSearch.getSelectedItem() == null) return;

    String keyword = txtSearch.getText().trim();
    String loai = cboLoaiSearch.getSelectedItem().toString();

    DefaultTableModel model = (DefaultTableModel) tblThuoc.getModel();
    model.setRowCount(0);

    List<Object[]> data;

    if (loai.equals("Tất cả")) {
        data = thuocCtrl.searchThuoc(keyword); // KHÔNG lọc loại
    } else {
        data = thuocCtrl.searchThuoc(keyword, loai); // có lọc loại
    }

    for (Object[] row : data) {
        model.addRow(row);
    }
}




