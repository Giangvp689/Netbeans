    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
         int row = tblThuoc.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn thuốc cần sửa");
            return;
        }

        if (!validateForm()) return;

        int idThuoc = Integer.parseInt(tblThuoc.getValueAt(row, 0).toString());

        Thuoc t = new Thuoc();
        t.setId_thuoc(idThuoc);
        t.setTenthuoc(txtTenThuoc.getText().trim());
        t.setLoai(cboLoaiThuoc.getSelectedItem().toString());
        t.setSoluongton(Integer.parseInt(txtSoLuong.getText().trim()));
        t.setDonvitinh(cboDVtinh.getSelectedItem().toString());
        t.setGiaban(new java.math.BigDecimal(txtGia.getText().trim()));
        t.setHansudung(new java.sql.Date(datePicker1.getDate().getTime()));
        t.setGhichu(txtGhiChu.getText().trim());

        if (thuocCtrl.updateThuoc(t)) {
            JOptionPane.showMessageDialog(this, "✔ Cập nhật thuốc thành công!");
            loadTableThuoc();
            resetForm();
        } else {
            JOptionPane.showMessageDialog(this, "❌ Cập nhật thất bại!");
        }
    }//GEN-LAST:event_btnSuaActionPerformed

