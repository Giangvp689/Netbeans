    private void tblThuocMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblThuocMouseClicked
       int row = tblThuoc.getSelectedRow();
    if (row < 0) return;

    // ID thuốc
    txtMaThuoc.setText(tblThuoc.getValueAt(row, 0).toString());

    // Tên thuốc
    txtTenThuoc.setText(tblThuoc.getValueAt(row, 1).toString());

    // Loại thuốc (ComboBox)
    cboLoaiThuoc.setSelectedItem(
        tblThuoc.getValueAt(row, 2) != null
            ? tblThuoc.getValueAt(row, 2).toString()
            : ""
    );

    // Số lượng
    txtSoLuong.setText(tblThuoc.getValueAt(row, 3).toString());

    // Đơn vị tính (ComboBox)
    cboDVtinh.setSelectedItem(
        tblThuoc.getValueAt(row, 4) != null
            ? tblThuoc.getValueAt(row, 4).toString()
            : ""
    );

    // Giá bán
    txtGia.setText(tblThuoc.getValueAt(row, 5).toString());

    // Hạn sử dụng
    datePicker1.setDate(
        tblThuoc.getValueAt(row, 6) != null
            ? (java.util.Date) tblThuoc.getValueAt(row, 6)
            : null
    );

    // Ghi chú
    txtGhiChu.setText(
        tblThuoc.getValueAt(row, 7) != null
            ? tblThuoc.getValueAt(row, 7).toString()
            : ""
    );
    }//GEN-LAST:event_tblThuocMouseClicked

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        // 1. Validate dữ liệu
    if (!validateForm()) return;

    // 2. Lấy dữ liệu từ form
    Thuoc t = new Thuoc();
    t.setTenthuoc(txtTenThuoc.getText().trim());
    t.setLoai(cboLoaiThuoc.getSelectedItem().toString());
    t.setSoluongton(Integer.parseInt(txtSoLuong.getText().trim()));
    t.setDonvitinh(cboDVtinh.getSelectedItem().toString());
    t.setGiaban(new java.math.BigDecimal(txtGia.getText().trim()));
    t.setHansudung(new java.sql.Date(datePicker1.getDate().getTime()));
    t.setGhichu(txtGhiChu.getText().trim());

    // 3. Gọi Controller
    if (thuocCtrl.addThuoc(t)) {
        JOptionPane.showMessageDialog(this, "✔ Thêm thuốc thành công!");
        loadTableThuoc();
        resetForm();
    } else {
        JOptionPane.showMessageDialog(this, "❌ Thêm thuốc thất bại!");
    }
    }//GEN-LAST:event_btnThemActionPerformed

