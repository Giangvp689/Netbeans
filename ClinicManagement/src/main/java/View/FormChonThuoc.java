    private void tblThuocMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblThuocMouseClicked
        int row=tblThuoc.getSelectedRow();
        if(row>=0){
            txtTenThuoc.setText(tblThuoc.getValueAt(row, 1).toString());
            lblDonGia.setText(tblThuoc.getValueAt(row, 5).toString());
        }
    }//GEN-LAST:event_tblThuocMouseClicked

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
      int row = tblThuoc.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this, "Chọn thuốc");
        return;
    }

    try {
        int idThuoc =
            Integer.parseInt(tblThuoc.getValueAt(row, 0).toString());
        int soLuong =
            Integer.parseInt(txtSoLuong.getText().trim());

        // ⚠ xử lý dấu , nếu có
        BigDecimal donGia =
            new BigDecimal(lblDonGia.getText().replace(",", ""));

        String lieuDung = txtLieuDung.getText();

        donThuocController.themThuocVaoDon(
            currentIdBa,
            idThuoc,
            soLuong,
            lieuDung,
            donGia
        );

        dispose(); // đóng popup

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnThemActionPerformed


