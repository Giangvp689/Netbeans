    private ThuocController thuocController=new ThuocController();
private void loadTableThuoc(String keyword) {
    DefaultTableModel model = new DefaultTableModel();
    model.setColumnIdentifiers(new Object[]{
        "Mã thuốc","Tên thuốc","Loại","Số lượng",
        "Đơn vị","Giá bán","Hạn sử dụng","Ghi chú"
    });

    for (Object[] row : thuocController.getThuocTableData(keyword)) {
        model.addRow(row);
    }
    tblThuoc.setModel(model);
}





