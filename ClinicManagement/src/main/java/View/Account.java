    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
         String username = txtusername.getText().trim();
        String password = txtpassword.getText().trim();
        String loaiTK = cboLoaiTK.getSelectedItem().toString();

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin");
            return;
        }

        int idRef = 0;

        if (!loaiTK.equals("ADMIN")) {
            if (cboTen.getSelectedItem() == null) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn đối tượng tham chiếu");
                return;
            }

            // "5 - Nguyễn Văn A"
            String selected = cboTen.getSelectedItem().toString();
            idRef = Integer.parseInt(selected.split("-")[0].trim());
        }

        AccountEntity acc = new AccountEntity();
        acc.setUsername(username);
        acc.setPasswordHash(password); // controller sẽ hash
        acc.setLoaiTk(loaiTK);
        acc.setIdRef(idRef);
        acc.setTrangThai("Hoạt động");

        // ===== GỌI CONTROLLER =====
        AccountController controller = new AccountController();
        if (controller.addAccount(acc)) {
            JOptionPane.showMessageDialog(this, "Thêm tài khoản thành công");
            loadTable();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại");
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
            int row = tblAccount.getSelectedRow();
            if (row < 0) {
                JOptionPane.showMessageDialog(this, "Chọn tài khoản cần sửa");
                return;
            }

            int idTk = Integer.parseInt(tblAccount.getValueAt(row, 0).toString());
            String password = txtpassword.getText().trim();
            String loaiTK = cboLoaiTK.getSelectedItem().toString();

            int idRef = 0;
            if (!loaiTK.equals("ADMIN")) {
                String selected = cboTen.getSelectedItem().toString();
                idRef = Integer.parseInt(selected.split("-")[0].trim());
            }

            AccountEntity acc = new AccountEntity();
            acc.setIdTk(idTk);
            acc.setPasswordHash(password);
            acc.setLoaiTk(loaiTK);
            acc.setIdRef(idRef);
            acc.setTrangThai("Hoạt động");

            AccountController controller = new AccountController();
            if (controller.updateAccount(acc)) {
                JOptionPane.showMessageDialog(this, "Cập nhật thành công");
                loadTable();
            } else {
                JOptionPane.showMessageDialog(this, "Cập nhật thất bại");
            }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        int row = tblAccount.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Chọn tài khoản cần xóa");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Bạn có chắc muốn xóa?",
            "Xác nhận",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) return;

        int idTk = Integer.parseInt(tblAccount.getValueAt(row, 0).toString());

        AccountController controller = new AccountController();
        if (controller.deleteAccount(idTk)) {
            JOptionPane.showMessageDialog(this, "Xóa thành công");
            loadTable();
        } else {
            JOptionPane.showMessageDialog(this, "Xóa thất bại");
        }
    }//GEN-LAST:event_btnXoaActionPerformed

    private void txtSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchKeyReleased
           String keyword = txtSearch.getText().trim();
            AccountController controller = new AccountController();

            if (keyword.isEmpty()) {
                loadTable(); // load lại toàn bộ
            } else {
                loadTable(controller.searchAccounts(keyword)); // realtime search
            }
    }//GEN-LAST:event_txtSearchKeyReleased

