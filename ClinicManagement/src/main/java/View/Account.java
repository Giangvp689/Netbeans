    private void loadTable(List<AccountEntity> list) {
    DefaultTableModel model = (DefaultTableModel) tblAccount.getModel();
    model.setRowCount(0);

    for (AccountEntity acc : list) {
        model.addRow(new Object[]{
            acc.getIdTk(),
            acc.getUsername(),
            acc.getLoaiTk(),
            acc.getIdRef(),
            acc.getTrangThai()
        });
    }
}

    
    
    
    private void loadNhanVien() {
    cboTen.removeAllItems();

    String sql = "SELECT id_nv, hoten FROM NhanVien WHERE trangthai = N'Đang làm việc'";

    try (Connection c = DBConnection.getConnection();
         PreparedStatement ps = c.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            cboTen.addItem(
                rs.getInt("id_nv") + " - " + rs.getString("hoten")
            );
        }
    } catch (Exception e) {
        e.printStackTrace();
    }
}
private void loadBacSi() {
    cboTen.removeAllItems();

    String sql = "SELECT id_bs, hoten FROM BacSi WHERE trangthai = N'Đang làm việc'";

    try (Connection c = DBConnection.getConnection();
         PreparedStatement ps = c.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            cboTen.addItem(
                rs.getInt("id_bs") + " - " + rs.getString("hoten")
            );
        }
    } catch (Exception e) {
        e.printStackTrace();
    }
}




