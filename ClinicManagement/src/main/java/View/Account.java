    private void loadTable() {
    DefaultTableModel model = new DefaultTableModel(
        new Object[][]{},
        new String[]{
            "ID",
            "Username",
            "Loại tài khoản",
            "Tham chiếu",
            "Trạng thái"
        }
    );

    tblAccount.setModel(model);

    AccountController controller = new AccountController();

    for (AccountEntity acc : controller.getAllAccounts()) {
        model.addRow(new Object[]{
            acc.getIdTk(),
            acc.getUsername(),
            acc.getLoaiTk(),
            acc.getTenThamChieu(), // 🔥 HIỂN THỊ TÊN
            acc.getTrangThai()
        });
    }
}


