    public void loadTable() {
            DefaultTableModel model = (DefaultTableModel) tblService.getModel();
            model.setRowCount(0); 

            model.setColumnIdentifiers(new Object[]{
                "MÃ DV", "Tên dịch vụ", "Loại dịch vụ", "Đơn giá", "Trạng Thái"
            });

            String sql = "SELECT madv, tendv, loai, dongia, trangthai FROM DichVu";

            try (Connection conn = DBConnection.getConnection(); 
                 PreparedStatement ps = conn.prepareStatement(sql);
                 ResultSet rs = ps.executeQuery()) {

                while (rs.next()) {
                    Vector row = new Vector();
                    row.add(rs.getString("madv"));
                    row.add(rs.getString("tendv"));
                    row.add(rs.getString("loai"));
                    row.add(rs.getDouble("dongia"));
                    row.add(rs.getString("trangthai"));

                    model.addRow(row); 
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Lỗi nạp dữ liệu: " + e.getMessage());
            }
        }
    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
    int selectedRow = tblService.getSelectedRow();
       if (selectedRow == -1) {
           JOptionPane.showMessageDialog(this, "Vui lòng chọn dòng cần xóa!");
           return;
       }

       String maDV = tblService.getValueAt(selectedRow, 0).toString();

       int confirm = JOptionPane.showConfirmDialog(
               this,
               "Bạn có chắc muốn xóa dịch vụ có mã: " + maDV + "?",
               "Xác nhận",
               JOptionPane.YES_NO_OPTION
       );

       if (confirm != JOptionPane.YES_OPTION) return;

       String sql = "DELETE FROM DichVu WHERE madv = ?";

       try (Connection conn = DBConnection.getConnection();
            PreparedStatement ps = conn.prepareStatement(sql)) {

           ps.setString(1, maDV);
           ps.executeUpdate();

           JOptionPane.showMessageDialog(this, "Xóa thành công!");
           loadTable();
       } catch (Exception e) {
           JOptionPane.showMessageDialog(this, "Lỗi xóa dịch vụ: " + e.getMessage());
       }
    }//GEN-LAST:event_btnXoaActionPerformed

