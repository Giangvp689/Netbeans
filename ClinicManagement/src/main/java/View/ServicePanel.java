        private void timKiem() {
            DefaultTableModel model = (DefaultTableModel) tblService.getModel();
            model.setRowCount(0);

            String keyword = txtSearch.getText().trim();
            String loaiDV = jComboBox3.getSelectedItem().toString();

            String sql = "SELECT madv, tendv, loai, dongia, trangthai FROM DichVu WHERE 1=1";

            if (!keyword.isEmpty()) {
                sql += " AND tendv LIKE ?";
            }
            if (!loaiDV.equals("Tất cả")) {
                sql += " AND loai = ?";
            }

            try (Connection conn = DBConnection.getConnection();
                 PreparedStatement ps = conn.prepareStatement(sql)) {

                int index = 1;
                if (!keyword.isEmpty()) {
                    ps.setString(index++, "%" + keyword + "%");
                }
                if (!loaiDV.equals("Tất cả")) {
                    ps.setString(index++, loaiDV);
                }

                ResultSet rs = ps.executeQuery();
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getString("madv"),
                        rs.getString("tendv"),
                        rs.getString("loai"),
                        rs.getDouble("dongia"),
                        rs.getString("trangthai")
                    });
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Lỗi tìm kiếm: " + e.getMessage());
            }
        }


