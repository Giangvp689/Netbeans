    private void phanQuyenMenu() {
        btnDoctors.setVisible(false);
        btnPatients.setVisible(false);
        btnMedical.setVisible(false);
        btnMedicine.setVisible(false);
        btnInvoice.setVisible(false);
        btnService.setVisible(false);
        btnEmployees.setVisible(false);
        btnReports.setVisible(false);
        btnAccount.setVisible(false);

        if (role == null) return;

        switch (role) {

            case "ADMIN":
                btnDoctors.setVisible(true);
                btnPatients.setVisible(true);
                btnMedical.setVisible(true);
                btnMedicine.setVisible(true);
                btnInvoice.setVisible(true);
                btnService.setVisible(true);
                btnEmployees.setVisible(true);
                btnReports.setVisible(true);
                btnAccount.setVisible(true);
                break;

            case "BACSI":
                btnPatients.setVisible(true);
                btnMedical.setVisible(true);
                break;

            case "NHANVIEN":
                btnMedical.setVisible(true);
                btnService.setVisible(true);
                btnInvoice.setVisible(true);
                break;
        }
    }

