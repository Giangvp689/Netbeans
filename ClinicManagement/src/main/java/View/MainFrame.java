    private void btnSettingMouseEntered(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnSettingMouseEntered
  JPopupMenu popup = new JPopupMenu();

    JMenuItem dark = new JMenuItem("Dark mode");
    JMenuItem light = new JMenuItem("Light mode");
    JMenuItem changePass = new JMenuItem("Change Password");

    popup.add(dark);
    popup.add(light);
    popup.addSeparator();
    popup.add(changePass);

    dark.addActionListener(e -> {
        com.formdev.flatlaf.FlatDarkLaf.setup();
        SwingUtilities.updateComponentTreeUI(this);
    });

    light.addActionListener(e -> {
        com.formdev.flatlaf.FlatLightLaf.setup();
        SwingUtilities.updateComponentTreeUI(this);
    });

    // 👉 CHANGE PASSWORD
    changePass.addActionListener(e -> {
        ChangePasswordDialog dialog =
                new ChangePasswordDialog(this, true);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
    });

    popup.show(btnSetting, 0, btnSetting.getHeight());
    }//GEN-LAST:event_btnSettingMouseEntered

