     private void loadTable() {
         List<BacSi> list = controller.getAllBacSi();
         DefaultTableModel model = new DefaultTableModel();

         model.setColumnIdentifiers(new Object[] {
             "ID", "Họ tên", "Chuyên môn", "Giới tính",
             "Ngày sinh", "SĐT", "Email", "Địa chỉ", 
             "Ghi chú", "Trạng thái",
             "Ngày bắt đầu", "Ngày kết thúc",
             "Giờ bắt đầu", "Giờ kết thúc",
             "Thứ làm việc"
         });

         for (BacSi bs : list) {

             // Lấy tất cả lịch của bác sĩ
             List<LichLamViec> listLLV = lich.getLichLamViecByBacSi(bs.getId_bs());

             Date ngayBD = null;
             Date ngayKT =null;
             String gioBD = "";
             String gioKT = "";
             String thu = "";

             if (listLLV != null && !listLLV.isEmpty()) {

                 // Lấy ngày bắt đầu nhỏ nhất, ngày kết thúc lớn nhất
                 Date minBD = listLLV.get(0).getNgaybatdau();
                 Date maxKT = listLLV.get(0).getNgayketthuc();

                 StringBuilder sbGioBD = new StringBuilder();
                 StringBuilder sbGioKT = new StringBuilder();
                 StringBuilder sbThu = new StringBuilder();

                 for (LichLamViec llv : listLLV) {
                     // Tìm min / max ngày
                     if (llv.getNgaybatdau().before(minBD)) minBD = llv.getNgaybatdau();
                     if (llv.getNgayketthuc().after(maxKT)) maxKT = llv.getNgayketthuc();

                     sbGioBD.append(llv.getGiobatdau()).append(" | ");
                     sbGioKT.append(llv.getGioketthuc()).append(" | ");
                     sbThu.append(llv.getThu()).append(", ");
                 }

                 // Chuyển thành chuỗi
                 ngayBD = minBD;
                    ngayKT = maxKT;


                 gioBD = sbGioBD.substring(0, sbGioBD.length() - 3); // bỏ dấu | cuối
                 gioKT = sbGioKT.substring(0, sbGioKT.length() - 3); 
                 thu = sbThu.substring(0, sbThu.length() - 2);       // bỏ dấu , cuối
             }

             model.addRow(new Object[] {
                 bs.getId_bs(), bs.getHoten(), bs.getChuyenmon(),
                 bs.getGioitinh(), bs.getNgaysinh(), bs.getSdt(),
                 bs.getEmail(), bs.getDiachi(), bs.getGhichu(), bs.getTrangthai(),
                 ngayBD, ngayKT, gioBD, gioKT, thu
             });
         }

         tblBacSi.setModel(model);
     }


