    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    int row = tblBacSi.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this, "Hãy chọn bác sĩ cần xóa!");
        return;
    }
    int confirm = JOptionPane.showConfirmDialog(this,
        "Bạn có chắc muốn xóa bác sĩ này?",
        "Xác nhận",
        JOptionPane.YES_NO_OPTION);
    if (confirm == JOptionPane.YES_OPTION) {
        int idBS = Integer.parseInt(tblBacSi.getValueAt(row, 0).toString());
        // Xóa lịch trước rồi xóa bác sĩ
        lich.deleteLlvBS(idBS);
        boolean success = controller.deleteBacSi(idBS);
        if (success) {
            loadTable();
            JOptionPane.showMessageDialog(this, "Xóa thành công!");
        } else {
            JOptionPane.showMessageDialog(this, "Xóa thất bại!");
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

