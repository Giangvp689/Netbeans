    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
       try {
        // --- VALIDATION ---
        if (txtHoten.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tên bác sĩ không được để trống!");
            return;
        }

        if (jDateChooserNgaySinh.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Chọn ngày sinh!");
            return;
        }

        if (dtNgayBd.getDate() == null || dtNgayKt.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Chọn ngày bắt đầu và kết thúc!");
            return;
        }

        if (tpGioBd.getTime() == null || tpGioKt.getTime() == null) {
            JOptionPane.showMessageDialog(this, "Chọn giờ làm việc!");
            return;
        }

        // --- Lấy danh sách thứ làm việc ---
        List<String> thuList = new ArrayList<>();
        if (chk2.isSelected()) thuList.add("2");
        if (chk3.isSelected()) thuList.add("3");
        if (chk4.isSelected()) thuList.add("4");
        if (chk5.isSelected()) thuList.add("5");
        if (chk6.isSelected()) thuList.add("6");
        if (chk7.isSelected()) thuList.add("7");
        if (chkCN.isSelected()) thuList.add("CN");

        if (thuList.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Chọn ít nhất một thứ làm việc!");
            return;
        }

        // --- TẠO BÁC SĨ ---
        BacSi bs = new BacSi();
        bs.setHoten(txtHoten.getText());
        bs.setChuyenmon(cbChuyenMon.getSelectedItem().toString());
        bs.setGioitinh(cbGioiTinh.getSelectedItem().toString());
        bs.setNgaysinh(jDateChooserNgaySinh.getDate());
        bs.setSdt(txtSDT.getText());
        bs.setEmail(txtEmail.getText());
        bs.setDiachi(txtDiaChi.getText());
        bs.setGhichu(txtGhiChu.getText());
        bs.setTrangthai(cbTrangThai.getSelectedItem().toString());

        // --- Thêm bác sĩ và lấy ID vừa tạo ---
        int idBS = controller.addBacSiReturnID(bs);

        if (idBS > 0) {
            // --- CHUYỂN NGÀY SANG java.sql.Date ---
            java.sql.Date ngayBD = new java.sql.Date(dtNgayBd.getDate().getTime());
            java.sql.Date ngayKT = new java.sql.Date(dtNgayKt.getDate().getTime());

            // --- CHUYỂN GIỜ TỪ LocalTime SANG java.sql.Time ---
            java.sql.Time sqlGioBD = java.sql.Time.valueOf(tpGioBd.getTime());
            java.sql.Time sqlGioKT = java.sql.Time.valueOf(tpGioKt.getTime());

            // --- THÊM LỊCH LÀM VIỆC ---
            for (String thu : thuList) {
                LichLamViec llv = new LichLamViec();
                llv.setId_bs(idBS);
                llv.setNgaybatdau(ngayBD);
                llv.setNgayketthuc(ngayKT);
                llv.setGiobatdau(sqlGioBD);
                llv.setGioketthuc(sqlGioKT);
                llv.setThu(thu);

                lich.addLichLamViec(llv);
            }

            loadTable();
            JOptionPane.showMessageDialog(this, "Thêm bác sĩ + lịch làm việc thành công!");
        } else {
            JOptionPane.showMessageDialog(this, "Thêm bác sĩ thất bại!");
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Có lỗi xảy ra!");
    }
    }//GEN-LAST:event_btnAddActionPerformed

    private void tblBacSiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBacSiMouseClicked
       int row = tblBacSi.getSelectedRow();
    if (row >= 0) {
        txtID.setText(tblBacSi.getValueAt(row, 0).toString());
        txtHoten.setText(tblBacSi.getValueAt(row, 1).toString());
        cbChuyenMon.setSelectedItem(tblBacSi.getValueAt(row, 2));
        cbGioiTinh.setSelectedItem(tblBacSi.getValueAt(row, 3));
        jDateChooserNgaySinh.setDate((Date) tblBacSi.getValueAt(row, 4));
        txtSDT.setText(tblBacSi.getValueAt(row, 5).toString());
        txtEmail.setText(tblBacSi.getValueAt(row, 6).toString());
        txtDiaChi.setText(tblBacSi.getValueAt(row, 7).toString());
        txtGhiChu.setText(tblBacSi.getValueAt(row, 8).toString());
        cbTrangThai.setSelectedItem(tblBacSi.getValueAt(row, 9));
        dtNgayBd.setDate((Date) tblBacSi.getValueAt(row, 10));
        dtNgayKt.setDate((Date) tblBacSi.getValueAt(row, 11));
       
        String gioBD = tblBacSi.getValueAt(row, 12).toString();
        if (!gioBD.isEmpty()) {
            String firstTime = gioBD.split("\\|")[0].trim();
            LocalTime lt = LocalTime.parse(firstTime);
            tpGioBd.setTime(lt);
        }

        String gioKT = tblBacSi.getValueAt(row, 13).toString();
        if (!gioKT.isEmpty()) {
            String firstTime = gioKT.split("\\|")[0].trim();
            LocalTime lt2 = LocalTime.parse(firstTime);
            tpGioKt.setTime(lt2);
        }

        String thuLamViec = tblBacSi.getValueAt(row, 14).toString();
        String[] arrThu = thuLamViec.split(",\\s*");

        chk2.setSelected(false);
        chk3.setSelected(false);
        chk4.setSelected(false);
        chk5.setSelected(false);
        chk6.setSelected(false);
        chk7.setSelected(false);
        chkCN.setSelected(false);

        for (String t : arrThu) {
            t = t.trim();

            // Nếu dữ liệu là dạng "Thứ 2,4,6"
            if (t.equals("2")) t = "Thứ 2";
            if (t.equals("3")) t = "Thứ 3";
            if (t.equals("4")) t = "Thứ 4";
            if (t.equals("5")) t = "Thứ 5";
            if (t.equals("6")) t = "Thứ 6";
            if (t.equals("7")) t = "Thứ 7";
            if (t.equalsIgnoreCase("CN")) t = "Chủ nhật";

            switch (t) {
                case "Thứ 2": chk2.setSelected(true); break;
                case "Thứ 3": chk3.setSelected(true); break;
                case "Thứ 4": chk4.setSelected(true); break;
                case "Thứ 5": chk5.setSelected(true); break;
                case "Thứ 6": chk6.setSelected(true); break;
                case "Thứ 7": chk7.setSelected(true); break;
                case "Chủ nhật": chkCN.setSelected(true); break;
            }
        }

        
        

    }
    }//GEN-LAST:event_tblBacSiMouseClicked

